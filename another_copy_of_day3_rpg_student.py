# ── Monk — the HARD conversion: SEVEN prints in one method ──────────────────
#     You cannot swap each print for a return — the first one ends the method.
#     Instead: flavour goes in a VARIABLE, add with +=, return ONCE at the end.
#     Also note the guard clause on line 1 — it removes a level of indentation.
class Monk(Character):
    CLASS_NAME = "Monk"
    EMOJI      = "🧘"

    def __init__(self, name):
        super().__init__(name)
        self.hit = False

    def special_attack(self, other):
        if self.mana < 30:
            return f"❌ {self.name} doesn't have enough mana for a great hit!"

        self.mana -= 30

        if self.hit:
            damage, crit = self.crit_check(random.randint(25, 50))
            other.health = max(0, other.health - damage)
            msg = f"🧘 Monk {self.name} uses a large attack for **{damage}** damage!"
            return msg + " 🔥 *Critical hit!*" if crit else msg

        self.hit = True
        roll = random.randint(0, 100)

        if   roll == 0:   flavour = "Monk misses!"
        elif roll <  10:  flavour = "Monk's focus is off! Low damage!"
        elif roll <  20:  flavour = "Monk is a bit off on the hit. Close to a miss!"
        elif roll <  70:  flavour = "Monk does good damage, focus is good!"
        elif roll <  90:  flavour = "Monk's focus is perfect! Deals good damage."
        elif roll < 100:  flavour = "Monk does a heavy hit! Aim is to be the best!"
        else:             flavour = "WOW! Monk does a PERFECT hit!!! Most damage done!"

        msg = f"🧘 {self.name} the Monk focuses! Ready to hit!\n\n*{flavour}*"

        if roll > 0:
            damage, crit = self.crit_check(roll)
            other.health = max(0, other.health - damage)
            msg += f"\n\nThe Monk strikes {other.name} for **{damage}** damage!"
            if crit:
                msg += " 🔥 *Critical hit!*"

        return msg


# ── Boss — your Day 2 AI, converted (given) ─────────────────────────────────
class Boss(Character):
    CLASS_NAME = "Boss"
    EMOJI      = "👹"

    def __init__(self):
        super().__init__("Doom Bringer")
        self.health = self.max_health = 150
        self.mana   = self.max_mana   = 40

    def special_move(self, target):
        if self.mana < 20:
            return self.basic_attack(target)

        damage, crit = self.crit_check(random.randint(40, 50))
        self.mana    -= 20
        target.health = max(0, target.health - damage)

        msg  = "💢 Doom Bringer unleashes **Desolation Wave**!"
        msg += f"\n\n💀 {target.name} is hit for **{damage}** massive damage!"
        if crit:
            msg += " 🔥 *Critical hit!*"
        return msg

    def choose_ai_action(self, target):
        options = []
        if self.health < 60 and self.mana >= 10:
            options.append(("heal",     40 + (60 - self.health)))
        if self.mana < 10:
            options.append(("meditate", 30 - self.mana))
        if self.mana >= 20:
            options.append(("special",  10 + (100 - target.health)))
        options.append(("basic",         5 + random.randint(0, 5)))

        best = max(options, key=lambda x: x[1])[0]

        if best == "heal":     return self.heal()
        if best == "meditate": return self.meditate()
        if best == "special":  return self.special_move(target)
        return self.basic_attack(target)


