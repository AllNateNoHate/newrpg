class Character:
    def __init__(self, name):
        self.name       = name
        self.health     = 100
        self.max_health = 100
        self.mana       = 50
        self.max_mana   = 50

    def is_alive(self):
        return self.health > 0

    def crit_check(self, damage):
        if random.random() < 0.2:
            return damage * 2, True
        return damage, False

    def basic_attack(self, other):
        damage, crit = self.crit_check(random.randint(5, 10))
        other.health = max(0, other.health - damage)
        msg = f"{self.name} punches {other.name} for **{damage}** damage!"
        return msg + " 🔥 *Critical hit!*" if crit else msg

    def heal(self):
        if self.mana >= 10:
            amount      = random.randint(15, 25)
            self.mana  -= 10
            self.health = min(self.health + amount, self.max_health)
            return f"💚 {self.name} heals for **{amount}** HP!"
        return f"❌ {self.name} doesn't have enough mana to heal!"

    def meditate(self):
        regen     = random.randint(10, 20)
        self.mana = min(self.mana + regen, self.max_mana)
        return f"✨ {self.name} meditates and restores **{regen}** mana."


